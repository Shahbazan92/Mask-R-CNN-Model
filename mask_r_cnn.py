import matplotlib.pyplot as plt
import random

# Put model in evaluation mode
model.eval()

# Get class names from dataset
class_names = full_dataset.classes

# Select 10 random indices from the test dataset
random.seed(42)  # For reproducibility
sample_indices = random.sample(range(len(test_dataset)), 10)

fig, axes = plt.subplots(2, 5, figsize=(15, 7))
axes = axes.ravel()

with torch.no_grad():
    for i, idx in enumerate(sample_indices):
        # Get image tensor and label
        image_tensor, true_label_idx = test_dataset[idx]

        # Predict
        input_tensor = image_tensor.unsqueeze(0).to(device) # Add batch dimension
        outputs = model(input_tensor)
        _, pred_label_idx = outputs.max(1)

        pred_class = class_names[pred_label_idx.item()]
        true_class = class_names[true_label_idx]

        # Denormalize image for displaying (for PyTorch visualization)
        # Normalization was: mean=[0.485, 0.456, 0.406], std=[0.229, 0.224, 0.225]
        img_disp = image_tensor.permute(1, 2, 0).numpy() # Convert from (C, H, W) to (H, W, C)
        mean = np.array([0.485, 0.456, 0.406])
        std = np.array([0.229, 0.224, 0.225])
        img_disp = std * img_disp + mean
        img_disp = np.clip(img_disp, 0, 1)

        # Plot
        axes[i].imshow(img_disp)
        axes[i].axis('off')

        # Green title if correct, red if incorrect
        color = 'green' if pred_class == true_class else 'red'
        axes[i].set_title(f"Actual: {true_class}\nPred: {pred_class}", color=color, fontsize=10)

plt.tight_layout()
plt.show()

